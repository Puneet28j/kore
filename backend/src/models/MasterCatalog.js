const mongoose = require("mongoose");

// हर size ke andar qty + sku
const SizeCellSchema = new mongoose.Schema(
  {
    qty: { type: Number, default: 0, min: 0 },
    sku: { type: String, trim: true, default: "" },
  },
  { _id: false }
);

const ImageItemSchema = new mongoose.Schema(
  {
    url: { type: String, required: true },
    key: { type: String, default: "" },
    isCover: { type: Boolean, default: false },
  },
  { _id: false }
);

const ColorMediaSchema = new mongoose.Schema(
  {
    color: { type: String, trim: true, required: true },
    images: { type: [ImageItemSchema], default: [] },
  },
  { _id: false }
);

const VariantSchema = new mongoose.Schema(
  {
    itemName: { type: String, required: true, trim: true },

    costPrice: { type: Number, default: 0, min: 0 },
    sellingPrice: { type: Number, default: 0, min: 0 },
    mrp: { type: Number, default: 0, min: 0 },
    hsnCode: { type: String, trim: true, default: "" },

    color: { type: String, trim: true, default: "" },
    sizeRange: { type: String, trim: true, default: "" },

    // ✅ duplicate same sizeRange support ke liye
    sizeRangeId: { type: String, trim: true, default: "" },

    sizeMap: {
      type: Map,
      of: SizeCellSchema,
      default: {},
    },

    sizeQuantities: {
      type: Map,
      of: Number,
      default: {},
    },

    sizeSkus: {
      type: Map,
      of: String,
      default: {},
    },

    // Channel tag — online or offline
    tag: {
      type: String,
      enum: ["online", "offline"],
      default: "online",
    },
    onlineMrp:  { type: Number, default: 0, min: 0 },
    offlineMrp: { type: Number, default: 0, min: 0 },

    // Carton-level SKU (e.g. slk-blk-5-9); sizeSkus auto-derived from this
    sku: { type: String, trim: true, default: "" },

    // Carton codes generated by manual stock inward that are in stock and not yet dispatched
    availableCartons: { type: [String], default: [] },

    isActive: { type: Boolean, default: true },

    // Per-variant override of the article-level stage/expectedAvailableDate
    // below — lets a PREORDER article's variants arrive (via GRN) and go
    // AVAILABLE independently of each other. Left undefined (not defaulted
    // to "AVAILABLE") on purpose: every reader falls back to the parent
    // article's stage when a variant hasn't set its own yet, so existing
    // data needs no migration.
    stage: { type: String, enum: ["AVAILABLE", "PREORDER"], default: undefined },
    expectedAvailableDate: { type: Date, default: undefined },
  },
  { _id: true }
);

const MasterCatalogSchema = new mongoose.Schema(
  {
    articleName: { type: String, required: true, trim: true },
    soleColor: { type: String, trim: true, default: "" },
    mrp: { type: Number, required: true, min: 0 },

    gender: {
      type: String,
      enum: ["MEN", "WOMEN", "KIDS", "UNISEX"],
      required: true,
    },

    categoryId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Category",
      required: true,
    },
    brandId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Brand",
      required: true,
    },
    manufacturerCompanyId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Manufacturer",
      required: true,
    },
    unitId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Unit",
      required: true,
    },

    productColors: [{ type: String, trim: true }],
    sizeRanges: [{ type: String, trim: true }],

    stage: {
      type: String,
      enum: ["AVAILABLE", "PREORDER"],
      default: "AVAILABLE",
    },
    expectedAvailableDate: { type: Date },

    primaryImage: {
      url: { type: String, default: "" },
      key: { type: String, default: "" },
    },
    secondaryImages: [
      {
        url: { type: String, default: "" },
        key: { type: String, default: "" },
      },
    ],

    colorMedia: {
      type: [ColorMediaSchema],
      default: [],
    },

    variants: {
      type: [VariantSchema],
      default: [],
    },

    isActive: { type: Boolean, default: true, index: true },
    isDeleted: { type: Boolean, default: false, index: true },
  },
  { timestamps: true }
);

MasterCatalogSchema.pre("validate", function () {
  if (this.stage === "PREORDER" && !this.expectedAvailableDate) {
    this.invalidate(
      "expectedAvailableDate",
      "expectedAvailableDate is required when stage is PREORDER"
    );
  }
});

module.exports = mongoose.model("MasterCatalog", MasterCatalogSchema);